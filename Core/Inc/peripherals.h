/* ENCODER DEFINITIONS */

/* Example: If an encoder has 30 mechanical detents and outputs 30 pulses on one turn of the encoder shaft, the encoder is matched.
 * Inversely, if the encoder has 30 mechanical detents and outputs 15 pulses, the encoder is unmatched.*/

/* The table below shows the states of an UNMATCHED encoder based on its channels' input signals.
 * The signals below will be concatenated in the order that they are shown, creating a 4-bit pattern.
 *
 * enc_ch_a_prev	enc->ch_a	enc_ch_b_prev		enc->ch_b	enc->state
 * 		1				1				1				1		ENC_STATE_RST
 * 		0				0				0				0		ENC_STATE_RST
 * 		--------------------------------------------------
 * 		0				0				1				0		ENC_STATE_CW
 * 		1				1				0				1		ENC_STATE_CW
 * 		--------------------------------------------------
 * 		1				0				0				0		ENC_STATE_CCW
 * 		0				1				1				1		ENC_STATE_CCW
 * 		*/

/* The table below shows the states of an MATCHED encoder based on its channels' input signals.
 *
 * enc_ch_a_prev	enc->ch_a	enc_ch_b_prev		enc->ch_b	enc->state
 * 		1				1				1				1		ENC_STATE_RST
 * 		0				0				0				0		ENC_STATE_RST
 * 		--------------------------------------------------
 * 		0				0				1				0		ENC_STATE_CW
 * 		--------------------------------------------------
 * 		1				0				0				0		ENC_STATE_CCW
 * 		*/

typedef enum{
	ENC_RST1 	= 0b0000, /** Reset pattern (1) for UNMATCHED and MATCHED encoders */
	ENC_RST2 	= 0b1111, /** Reset pattern (2) for UNMATCHED and MATCHED encoders */

	ENC_CW1 	= 0b0010, /** Clock-wise pattern (1) for UNMATCHED and MATCHED encoders */
	ENC_CW2 	= 0b1101,  /** Clock-wise pattern (2) for UNMATCHED encoders */

	ENC_CCW1 	= 0b1000, /** Counter clock-wise pattern (1) for UNMATCHED and MATCHED encoders */
	ENC_CCW2 	= 0b0111,  /** Counter clock-wise pattern (2) for only UNMATCHED encoders */
} EncoderSignal;

typedef enum{
	ENC_STATE_RST, /** Reset state for encoder */
	ENC_STATE_CW,  /** Clock-wise state for encoder */
	ENC_STATE_CCW  /** Counter clock-wise state for encoder */
} EncoderState;

typedef enum{
	ENC_MODE_UNMATCHED = 0x02, /* Panel uses encoders with unmatched detents and PPR (Pulses Per Rotation) */
	ENC_MODE_MATCHED = 0x01 /* Panel uses encoders with matched detents and PPR (Pulses Per Rotation) */
} EncoderMode;

/**@brief Incremental encoder container */
typedef struct {
	PeripheralID id;						/* Encoder identifier - Used when determining what commands shall be generated by encoder actions */
	EncoderMode mode; 					/* Defines the encoder as matched or unmatched */
	uint8_t init_flag;				/* Flags if encoder is initialized (PERIPH_INIT) or not (PERIPH_NOT_INIT) */
	EncoderState state;					/* Encoder state-machine */
	uint8_t ch_a, ch_b;				/* Encoder channel variables*/

	GPIO_TypeDef *PORT_A, *PORT_B; 	/* Encoder channels' ports */
	uint16_t PIN_A, PIN_B; 			/* Encoder channels' input pins */
} Encoder;

void Peripheral_EncoderInit(Encoder *enc, PeripheralID id, EncoderMode mode, GPIO_TypeDef *PORT_A, uint16_t PIN_A, GPIO_TypeDef *PORT_B, uint16_t PIN_B);
void Peripheral_EncoderScan(Encoder *enc);
void Peripheral_EncoderExec(Encoder *enc);


