/* The table below shows the states of an active-low button.
 * The signals below will be concatenated in the order that they are shown, creating a 2-bit pattern.
 *
 * btn_sig_prev		btn->sig		btn->state
 * 		1				1		BTN_STATE_RST 	(active-low)
 * 		0				0		BTN_STATE_RST	(active-high)
 * 		--------------------------------------------------
 * 		1				0		BTN_STATE_PRESS	(active-low)
 * 		0				1		BTN_STATE_PRESS	(active-high)
 * 		--------------------------------------------------
 * 		0				0		BTN_STATE_HOLD	(active-low)
 * 		1				1		BTN_STATE_HOLD	(active-high)
 * 		--------------------------------------------------
 * 		0				1		BTN_STATE_REL	(active-low)
 * 		1				0		BTN_STATE_REL	(active-high)
 *		*/

typedef enum{
	BTN_LO_RST		= 0b11,
	BTN_HI_RST		= 0b00,
	BTN_LO_PRESS	= 0b10,
	BTN_HI_PRESS	= 0b01,
	BTN_LO_HOLD		= 0b00,
	BTN_HI_HOLD		= 0b11,
	BTN_LO_REL		= 0b01,
	BTN_HI_REL		= 0b10
} ButtonSignal;

typedef enum{
	BTN_STATE_RST, 
	BTN_STATE_PRESS,
	BTN_STATE_HOLD,
	BTN_STATE_REL
} ButtonState;

